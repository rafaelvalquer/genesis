import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.argv[2] || process.cwd());
const read = (rel) => fs.readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n");
const exists = (rel) => fs.existsSync(path.join(root, rel));
const checks = [];
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) });

const battle = read("src/game/battleModel.js");
const canvas = read("src/game/GameCanvas.jsx");
const pulse = read("src/game/dematerializationPulse.js");
const agent = read("src/game/simulation/ai/StrategicAgent.js");
const actions = read("src/game/simulation/engine/simulationActions.js");
const observation = read("src/game/simulation/observation/createBattleObservation.js");
const profiles = read("src/game/simulation/strategies/strategyProfiles.js");
const optimizer = read("src/game/simulation/optimization/PolicyOptimizer.js");
const metrics = read("src/game/simulation/metrics/SimulationMetrics.js");
const planner = read("src/game/simulation/planners/DematerializationPulsePlanner.js");
const graphics = read("src/game/graphicsRuntime.js");

check("módulo de domínio existe", exists("src/game/dematerializationPulse.js"));
check("dano fixo 500", /damage:\s*500/.test(pulse));
check("estado por rota centralizado", pulse.includes("createDematerializationPulseState"));
check("battleModel usa módulo central", battle.includes('from "./dematerializationPulse.js"'));
check("constante antiga removida", !battle.includes("export const DEMATERIALIZATION_PULSE = {"));
check("API pública de ativação", battle.includes("export function activateDematerializationPulse"));
check("automático usa mesma API", battle.includes('source: "automatic"') && battle.includes('reason: "barrierBreach"'));
check("dano parcial em vez de execução total", battle.includes("applyDematerializationPulseDamage") && battle.includes("hpBefore - damage"));
check("evento de hit do pulso", battle.includes('type: "pulseHit"'));
check("evento de resolução do pulso", battle.includes('type: "pulseResolved"'));
check("graphicsRuntime reage ao hit do pulso", graphics.includes("pulseHit: 1.1") && graphics.includes('"pulseHit"].includes(event.type)'));
check("UI de canhão existe", exists("src/game/components/DematerializationPulseControls.jsx"));
check("UI mostra 500 do domínio", read("src/game/components/DematerializationPulseControls.jsx").includes("DEMATERIALIZATION_PULSE.damage"));
check("GameCanvas renderiza controles", canvas.includes("<DematerializationPulseControls"));
check("GameCanvas ativa API pública", canvas.includes("handleActivateDematerializationPulse") && canvas.includes("activateDematerializationPulse(sessionRef.current"));
check("planner de pulso existe", exists("src/game/simulation/planners/DematerializationPulsePlanner.js"));
check("planner calcula colapso", planner.includes("calculateDematerializationPulseCollapseScore"));
check("planner calcula dano útil", planner.includes("estimateDematerializationPulseValue"));
check("StrategicAgent usa planner", agent.includes("planDematerializationPulseActions"));
check("ação de IA executável", actions.includes('case "activateDematerializationPulse"'));
check("observação expõe defesas", observation.includes("defenses:") && observation.includes("dematerializationPulses:"));
check("perfil possui thresholds", profiles.includes("pulseRiskThreshold") && profiles.includes("pulseEmergencyTimeMs") && profiles.includes("pulseMinimumValue"));
check("genoma inclui thresholds", profiles.match(/pulseRiskThreshold/g)?.length >= 2);
check("otimizador evolui thresholds", optimizer.includes("pulseRiskThreshold: [8, 30]") && optimizer.includes("pulseMinimumValue: [300, 1800]"));
check("métricas do pulso", metrics.includes("pulseActivations") && metrics.includes("pulseDamageByRow"));
check("testes de domínio", exists("src/game/dematerializationPulse.test.js"));
check("teste dos controles", exists("src/game/components/DematerializationPulseControls.test.jsx"));
check("testes do planner", exists("src/game/simulation/planners/DematerializationPulsePlanner.test.js"));

for (const item of checks) console.log(`${item.ok ? "OK" : "FALHA"} - ${item.name}`);
const failed = checks.filter((item) => !item.ok);
console.log(`\n${checks.length - failed.length}/${checks.length} verificações passaram.`);
if (failed.length) process.exit(1);
