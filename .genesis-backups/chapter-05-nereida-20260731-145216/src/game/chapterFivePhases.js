function createChapterFivePhase(blueprint, chapterIndex) {
  const waves = blueprint.waves.map((enemies) => ({ enemies }));

  return {
    ...blueprint,
    waves,
    energyMax: blueprint.energy,
    baseIntegrity: 100,
    chapterId: "chapter_05",
    chapterIndex,
    supplyLimit: 40,
    loadoutLimit: 8,
    waveCompletionEnergy: 20,
    environmentHazard: null,
    waveIntensity: waves.map((_, waveIndex) => (
      .38
      + .62
      * waveIndex
      / Math.max(1, waves.length - 1)
    )),
  };
}

